#!/usr/bin/env bash
# Helper functions for generate-inventory-step-ca.sh (sourced, not executed).
# shellcheck disable=SC2034  # variables are used by the entry script

SC_STEP_VERSION=${SC_STEP_VERSION:-0.28.6}
SC_DIR=${ANSIBLE_STEP_CA_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/ansible-step-ca}
SC_MARK='ansible-step-ca'

sc_info() { printf '%s\n' "$*"; }
sc_warn() { printf 'Warning: %s\n' "$*" >&2; }
sc_die() { printf 'Error: %s\n' "$*" >&2; exit 1; }

sc_ask() { # PROMPT DEFAULT -> REPLY
  local prompt=$1 default=${2:-}
  read -r -p "$prompt${default:+ [$default]}: " REPLY || exit 1
  REPLY=${REPLY:-$default}
}

# Locate a sibling repository, a vendored copy, or clone it into vendor/.
sc_find_repo() { # NAME MARKER_FILE -> prints directory
  local name=$1 marker=$2 dir
  for dir in "$SC_REPO_DIR/../$name" "$SC_REPO_DIR/vendor/$name"; do
    [[ -r $dir/$marker ]] && { (cd -- "$dir" && pwd); return 0; }
  done
  command -v git >/dev/null 2>&1 || sc_die "Clone https://github.com/Michdo93/$name next to this repository (git not found)."
  printf '%s was not found next to this repository; cloning it into vendor/.\n' "$name" >&2
  git clone -q --depth 1 "https://github.com/Michdo93/$name.git" "$SC_REPO_DIR/vendor/$name" >&2 || sc_die "git clone $name failed."
  (cd -- "$SC_REPO_DIR/vendor/$name" && pwd)
}

# Install the step CLI from the GitHub release if it is missing.
sc_ensure_step() {
  command -v step >/dev/null 2>&1 && return 0
  local arch dest tmp
  case $(uname -m) in
    x86_64) arch=amd64 ;; aarch64|arm64) arch=arm64 ;; armv7l) arch=armv7 ;; armv6l) arch=armv6 ;; i?86) arch=386 ;;
    *) sc_die "Unsupported architecture $(uname -m); install the step CLI manually." ;;
  esac
  bm_ask_yes_no "The step CLI is missing. Download step $SC_STEP_VERSION from GitHub and install it?" y || sc_die 'The step CLI is required.'
  command -v curl >/dev/null 2>&1 || sc_die 'curl is required to download step.'
  tmp=$(mktemp -d)
  curl -fsSL "https://github.com/smallstep/cli/releases/download/v$SC_STEP_VERSION/step_linux_${SC_STEP_VERSION}_$arch.tar.gz" \
    | tar -xz -C "$tmp" || sc_die 'Download of the step CLI failed.'
  if [[ $EUID -eq 0 ]]; then dest=/usr/local/bin/step; install -m 0755 "$tmp/step_$SC_STEP_VERSION/bin/step" "$dest"
  elif command -v sudo >/dev/null 2>&1 && sudo install -m 0755 "$tmp/step_$SC_STEP_VERSION/bin/step" /usr/local/bin/step; then dest=/usr/local/bin/step
  else dest=$HOME/.local/bin/step; install -D -m 0755 "$tmp/step_$SC_STEP_VERSION/bin/step" "$dest"; export PATH="$PATH:$HOME/.local/bin"; fi
  rm -rf -- "$tmp"
  sc_info "Installed $dest ($(step version 2>/dev/null | head -n1))."
}

sc_load_config() {
  [[ -r $SC_DIR/config.env ]] || return 1
  # shellcheck source=/dev/null
  . "$SC_DIR/config.env"
  [[ -n ${CA_URL:-} && -n ${CA_FINGERPRINT:-} ]]
}

sc_save_config() {
  install -d -m 0700 "$SC_DIR"
  umask 077
  cat > "$SC_DIR/config.env" <<EOF
# Generated by ansible-inventory-generator-step-ca
CA_URL=$(printf '%q' "$CA_URL")
CA_FINGERPRINT=$(printf '%q' "$CA_FINGERPRINT")
PROVISIONER=$(printf '%q' "$PROVISIONER")
KEY_FILE=$(printf '%q' "$KEY_FILE")
KEY_ID=$(printf '%q' "$KEY_ID")
PRINCIPALS=$(printf '%q' "$PRINCIPALS")
USER_CERT_DURATION=$(printf '%q' "$USER_CERT_DURATION")
HOST_CERT_DURATION=$(printf '%q' "$HOST_CERT_DURATION")
HOST_CERT_RENEW_BEFORE=$(printf '%q' "$HOST_CERT_RENEW_BEFORE")
INVENTORY_DIR=$(printf '%q' "$INVENTORY_DIR")
REPO_DIR=$(printf '%q' "$SC_REPO_DIR")
ANSIBLE_PLAYBOOK=$(printf '%q' "$(command -v ansible-playbook)")
REMOVE_STATIC_KEY=$(printf '%q' "$REMOVE_STATIC_KEY")
EOF
  cat > "$SC_DIR/enroll-vars.yml" <<EOF
---
# Generated by ansible-inventory-generator-step-ca (variables for playbooks/enroll.yml)
ssh_ca_dir: "$SC_DIR"
ssh_ca_steppath: "$SC_DIR/step"
ssh_ca_provisioner: "$PROVISIONER"
ssh_ca_provisioner_password_file: "$SC_DIR/provisioner-password"
ssh_ca_key_file: "$KEY_FILE"
ssh_ca_known_hosts: "$HOME/.ssh/known_hosts"
ssh_ca_user_cert_duration: "$USER_CERT_DURATION"
ssh_ca_host_cert_duration: "$HOST_CERT_DURATION"
ssh_ca_host_cert_renew_before: "$HOST_CERT_RENEW_BEFORE"
ssh_ca_remove_static_key: $REMOVE_STATIC_KEY
EOF
  install -m 0755 "$SC_REPO_DIR/bin/ssh-cert-refresh.sh" "$SC_DIR/ssh-cert-refresh.sh"
  install -m 0755 "$SC_REPO_DIR/bin/run-enroll.sh" "$SC_DIR/run-enroll.sh"
}

# Distinct ansible_user values of an INI inventory (the principals the cert needs).
sc_inventory_users() { # INVENTORY_FILE
  python3 - "$1" <<'PY'
import shlex, sys
users = []
section = ""
for raw in open(sys.argv[1], encoding="utf-8", errors="replace"):
    s = raw.strip()
    if s.startswith("[") and "]" in s:
        section = s[1:s.index("]")]
        continue
    if not s or s.startswith(("#", ";")) or ":" in section:
        continue
    try:
        tokens = shlex.split(s, comments=True)
    except ValueError:
        continue
    for t in tokens[1:]:
        if t.startswith("ansible_user="):
            u = t.split("=", 1)[1]
            if u and u not in users:
                users.append(u)
print(" ".join(users))
PY
}

# Inventory hosts as "alias address" lines.
sc_inventory_hosts() { # INVENTORY_FILE
  python3 - "$1" <<'PY'
import shlex, sys
section = ""
seen = set()
for raw in open(sys.argv[1], encoding="utf-8", errors="replace"):
    s = raw.strip()
    if s.startswith("[") and "]" in s:
        section = s[1:s.index("]")]
        continue
    if not s or s.startswith(("#", ";")) or ":" in section:
        continue
    tokens = shlex.split(s, comments=True)
    if not tokens or tokens[0] in seen:
        continue
    seen.add(tokens[0])
    v = dict(t.split("=", 1) for t in tokens[1:] if "=" in t)
    print(tokens[0], v.get("ansible_host", tokens[0]))
PY
}

# Timers: hourly user certificate refresh, daily enrollment run (host certificates).
sc_install_timers() { # WITH_ENROLL(true|false)
  local with_enroll=$1 user sudo=() systemd=false
  user=$(id -un)
  if [[ -d /run/systemd/system ]]; then
    if [[ $EUID -eq 0 ]]; then systemd=true
    elif command -v sudo >/dev/null 2>&1 && bm_ask_yes_no 'Install systemd timers (needs sudo)? No = use your crontab.' y; then
      sudo -v && { sudo=(sudo); systemd=true; }
    fi
  fi
  if [[ $systemd == true ]]; then
    "${sudo[@]}" tee /etc/systemd/system/ansible-step-ca-user-cert.service >/dev/null <<EOF
[Unit]
Description=Refresh the step-ca SSH user certificate of $user for Ansible
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
User=$user
Environment=ANSIBLE_STEP_CA_DIR=$SC_DIR
ExecStart=$SC_DIR/ssh-cert-refresh.sh
EOF
    "${sudo[@]}" tee /etc/systemd/system/ansible-step-ca-user-cert.timer >/dev/null <<'EOF'
[Unit]
Description=Refresh the step-ca SSH user certificate for Ansible every hour

[Timer]
OnBootSec=1min
OnCalendar=hourly
RandomizedDelaySec=120
Persistent=true

[Install]
WantedBy=timers.target
EOF
    local timers=(ansible-step-ca-user-cert.timer)
    if [[ $with_enroll == true ]]; then
      "${sudo[@]}" tee /etc/systemd/system/ansible-step-ca-enroll.service >/dev/null <<EOF
[Unit]
Description=Renew step-ca SSH host certificates via Ansible
Wants=network-online.target
After=network-online.target ansible-step-ca-user-cert.service

[Service]
Type=oneshot
User=$user
Environment=ANSIBLE_STEP_CA_DIR=$SC_DIR
ExecStartPre=$SC_DIR/ssh-cert-refresh.sh
ExecStart=$SC_DIR/run-enroll.sh
EOF
      "${sudo[@]}" tee /etc/systemd/system/ansible-step-ca-enroll.timer >/dev/null <<'EOF'
[Unit]
Description=Renew step-ca SSH host certificates via Ansible every day

[Timer]
OnCalendar=daily
RandomizedDelaySec=1800
Persistent=true

[Install]
WantedBy=timers.target
EOF
      timers+=(ansible-step-ca-enroll.timer)
    fi
    "${sudo[@]}" systemctl daemon-reload
    "${sudo[@]}" systemctl enable --now "${timers[@]}" >/dev/null
    sc_info "systemd timers active: ${timers[*]} (systemctl list-timers 'ansible-step-ca-*')."
    return 0
  fi
  command -v crontab >/dev/null 2>&1 || { sc_warn 'Neither systemd nor crontab is available; run ssh-cert-refresh.sh yourself at least every hour.'; return 1; }
  local current entries
  current=$(crontab -l 2>/dev/null | grep -v "# $SC_MARK" || true)
  entries="17 * * * * ANSIBLE_STEP_CA_DIR=$SC_DIR $SC_DIR/ssh-cert-refresh.sh >/dev/null 2>&1 # $SC_MARK
@reboot sleep 60; ANSIBLE_STEP_CA_DIR=$SC_DIR $SC_DIR/ssh-cert-refresh.sh >/dev/null 2>&1 # $SC_MARK"
  if [[ $with_enroll == true ]]; then
    entries+="
43 3 * * * ANSIBLE_STEP_CA_DIR=$SC_DIR $SC_DIR/run-enroll.sh >>$SC_DIR/enroll.log 2>&1 # $SC_MARK"
  fi
  printf '%s\n%s\n' "$current" "$entries" | sed '/^$/d' | crontab -
  sc_info "Cron jobs installed (crontab -l | grep $SC_MARK)."
}
